import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { STATUSES } from "./config.js";

// Read AND write tools. Every tool is bound to the uid from the verified
// OAuth access token — a caller can only ever touch their own applications
// under users/{uid}/applications. No tool accepts a uid parameter, there
// are no bulk operations, and all input is validated with zod before it
// reaches the store (unknown fields are rejected, status must be one of
// the known pipeline statuses).

const StatusEnum = z.enum(STATUSES);

// Writable application fields. `id` is deliberately absent: ids are
// generated by the store on add, and supplied separately on update/delete.
const ApplicationFields = {
  company: z.string().min(1).describe("Employer / company name."),
  role: z.string().min(1).describe("Job title / role."),
  location: z.string().describe("Job location."),
  type: z.string().describe("Employment type, e.g. Full-time, Part-time, Contract."),
  status: StatusEnum.describe("Pipeline status."),
  applied: z.string().describe("Date applied (YYYY-MM-DD)."),
  closing: z.string().describe("Posting closing date (YYYY-MM-DD)."),
  pay: z.string().describe("Pay, e.g. $65,000 or $24/hr."),
  req: z.string().describe("Requisition / job id."),
  url: z.string().describe("Link to the job posting."),
  notes: z.string().describe("Free-text notes."),
};

// Strict objects: unknown fields are rejected, not stripped.
const AddApplicationInput = z.strictObject({
  company: ApplicationFields.company,
  role: ApplicationFields.role,
  location: ApplicationFields.location.optional(),
  type: ApplicationFields.type.optional(),
  status: ApplicationFields.status.optional(),
  applied: ApplicationFields.applied.optional(),
  closing: ApplicationFields.closing.optional(),
  pay: ApplicationFields.pay.optional(),
  req: ApplicationFields.req.optional(),
  url: ApplicationFields.url.optional(),
  notes: ApplicationFields.notes.optional(),
});

const UpdateApplicationInput = z.strictObject({
  id: z.string().describe("The application id."),
  company: ApplicationFields.company.optional(),
  role: ApplicationFields.role.optional(),
  location: ApplicationFields.location.optional(),
  type: ApplicationFields.type.optional(),
  status: ApplicationFields.status.optional(),
  applied: ApplicationFields.applied.optional(),
  closing: ApplicationFields.closing.optional(),
  pay: ApplicationFields.pay.optional(),
  req: ApplicationFields.req.optional(),
  url: ApplicationFields.url.optional(),
  notes: ApplicationFields.notes.optional(),
});

const ApplicationSchema = z.object({
  id: z.string(),
  company: z.string(),
  role: z.string(),
  location: z.string(),
  type: z.string(),
  status: StatusEnum,
  applied: z.string(),
  closing: z.string(),
  pay: z.string(),
  req: z.string(),
  url: z.string(),
  notes: z.string(),
});

const READ_ONLY = {
  readOnlyHint: true,
  destructiveHint: false,
  idempotentHint: true,
  openWorldHint: false,
};

// Writes change the user's own data, so they are not read-only and not
// idempotent. Delete is destructive; add/update are not.
const WRITE = {
  readOnlyHint: false,
  destructiveHint: false,
  idempotentHint: false,
  openWorldHint: false,
};

const DESTRUCTIVE_WRITE = {
  readOnlyHint: false,
  destructiveHint: true,
  idempotentHint: false,
  openWorldHint: false,
};

function textResult(text, structuredContent) {
  const out = { content: [{ type: "text", text }] };
  if (structuredContent !== undefined) out.structuredContent = structuredContent;
  return out;
}

function notFoundResult(id) {
  return {
    content: [
      { type: "text", text: `No application found with id "${id}".` },
    ],
    isError: true,
  };
}

export function createMcpServer(uid, store) {
  const server = new McpServer(
    { name: "application-tracker", version: "1.1.0" },
    { capabilities: { tools: {} } },
  );

  server.registerTool(
    "list_applications",
    {
      title: "List applications",
      description:
        "List the user's job applications, newest first. Optionally filter by pipeline status.",
      inputSchema: {
        status: StatusEnum.optional().describe(
          "Only return applications in this pipeline status.",
        ),
        limit: z
          .number()
          .int()
          .min(1)
          .max(100)
          .optional()
          .describe("Maximum applications to return (default 50)."),
      },
      outputSchema: {
        applications: z.array(ApplicationSchema),
        count: z.number(),
      },
      annotations: READ_ONLY,
    },
    async ({ status, limit }) => {
      const applications = await store.listApplications(uid, {
        status,
        limit: limit ?? 50,
      });
      return textResult(JSON.stringify(applications, null, 2), {
        applications,
        count: applications.length,
      });
    },
  );

  server.registerTool(
    "get_application",
    {
      title: "Get application",
      description: "Get one application by its id.",
      inputSchema: {
        id: z.string().describe("The application id."),
      },
      outputSchema: {
        application: ApplicationSchema.nullable(),
      },
      annotations: READ_ONLY,
    },
    async ({ id }) => {
      const application = await store.getApplication(uid, id);
      if (!application) {
        return {
          content: [
            {
              type: "text",
              text: `No application found with id "${id}".`,
            },
          ],
          isError: true,
        };
      }
      return textResult(JSON.stringify(application, null, 2), { application });
    },
  );

  server.registerTool(
    "search_applications",
    {
      title: "Search applications",
      description:
        "Search the user's applications by text. Matches company, role, location, and notes (case-insensitive).",
      inputSchema: {
        query: z.string().min(1).describe("Text to search for."),
        limit: z
          .number()
          .int()
          .min(1)
          .max(100)
          .optional()
          .describe("Maximum applications to return (default 50)."),
      },
      outputSchema: {
        applications: z.array(ApplicationSchema),
        count: z.number(),
      },
      annotations: READ_ONLY,
    },
    async ({ query, limit }) => {
      const applications = await store.searchApplications(uid, {
        query,
        limit: limit ?? 50,
      });
      return textResult(JSON.stringify(applications, null, 2), {
        applications,
        count: applications.length,
      });
    },
  );

  server.registerTool(
    "get_stats",
    {
      title: "Get application stats",
      description:
        "Summary counts for the user's job search: total applications and counts by pipeline status.",
      inputSchema: {},
      outputSchema: {
        total: z.number(),
        byStatus: z.object(
          Object.fromEntries(STATUSES.map((s) => [s, z.number()])),
        ),
        active: z.number(),
        offers: z.number(),
        interviews: z.number(),
      },
      annotations: READ_ONLY,
    },
    async () => {
      const stats = await store.getStats(uid);
      return textResult(JSON.stringify(stats, null, 2), stats);
    },
  );

  server.registerTool(
    "add_application",
    {
      title: "Add application",
      description:
        "Add a new job application to the user's tracker. Company and role are required; everything else is optional and defaults to empty (status defaults to saved). Returns the created application with its generated id.",
      inputSchema: AddApplicationInput,
      outputSchema: {
        application: ApplicationSchema,
      },
      annotations: WRITE,
    },
    async (args) => {
      const application = await store.addApplication(uid, args);
      return textResult(JSON.stringify(application, null, 2), { application });
    },
  );

  server.registerTool(
    "update_application",
    {
      title: "Update application",
      description:
        "Update one of the user's applications by id. Only the fields provided change; everything else stays as it is. At least one field besides id must be provided. Updating an application that does not exist (or belongs to another user) is an error, never a create.",
      inputSchema: UpdateApplicationInput,
      outputSchema: {
        application: ApplicationSchema,
      },
      annotations: WRITE,
    },
    async ({ id, ...fields }) => {
      // Strip absent fields so only provided values change. Empty strings
      // are real values (e.g. clearing notes) and are kept.
      const patch = {};
      for (const [key, value] of Object.entries(fields)) {
        if (value !== undefined) patch[key] = value;
      }
      if (Object.keys(patch).length === 0) {
        return {
          content: [
            {
              type: "text",
              text: "Nothing to update: provide at least one field besides id.",
            },
          ],
          isError: true,
        };
      }
      const application = await store.updateApplication(uid, id, patch);
      if (!application) return notFoundResult(id);
      return textResult(JSON.stringify(application, null, 2), { application });
    },
  );

  server.registerTool(
    "delete_application",
    {
      title: "Delete application",
      description:
        "Permanently delete one of the user's applications by id. Deleting an application that does not exist (or belongs to another user) is an error.",
      inputSchema: {
        id: z.string().describe("The application id."),
      },
      outputSchema: {
        deleted: z.boolean(),
        id: z.string(),
      },
      annotations: DESTRUCTIVE_WRITE,
    },
    async ({ id }) => {
      const deleted = await store.deleteApplication(uid, id);
      if (!deleted) return notFoundResult(id);
      return textResult(`Deleted application "${id}".`, {
        deleted: true,
        id,
      });
    },
  );

  return server;
}
